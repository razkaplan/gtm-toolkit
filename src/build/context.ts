import type { ContentItem } from '../content/load';
import { RULES, resolveRule } from '../lint';
import type { Spec } from '../spec/schema';
import { crawlerDecisions } from './crawlers';

function bullets(values: string[]): string[] {
  return values.map((value) => `- ${value}`);
}

/**
 * GTM.md: the whole spec, compiled into one brief a coding agent can read in a
 * single pass and a new teammate can read in five minutes. Reference it from
 * AGENTS.md, CLAUDE.md or your editor rules.
 */
export function buildContext(spec: Spec, items: ContentItem[], specDir: string): string {
  const out: string[] = [
    `<!-- Generated by gtm-toolkit from ${specDir}/. Do not edit by hand: change the spec and run \`gtm build\`. -->`,
    '',
    `# GTM context: ${spec.site.name}`,
    '',
    'This file is the go-to-market source of truth for this repository, compiled for people and coding agents.',
    'Read it before writing or editing anything customer-facing: pages, posts, docs, UI copy, metadata.',
    '',
    `- Site: ${spec.site.url}`,
    `- What it is: ${spec.site.description}`,
  ];
  if (spec.owner) {
    out.push(`- Owner: ${spec.owner.name}${spec.owner.jobTitle ? `, ${spec.owner.jobTitle}` : ''} (${spec.owner.type})`);
  }
  out.push('');

  const positioning = spec.positioning;
  if (positioning) {
    out.push('## Positioning', '', `- Category: ${positioning.category}`, `- One-liner: ${positioning.oneLiner}`);
    if (positioning.tagline) out.push(`- Tagline: ${positioning.tagline}`);
    out.push(`- Problem: ${positioning.problem}`);
    if (positioning.audience.length > 0) out.push(`- Audience, in priority order: ${positioning.audience.join(', ')}`);
    out.push('');
    if (positioning.differentiators.length > 0) {
      out.push('### Why us', '');
      for (const item of positioning.differentiators) {
        out.push(`- **${item.claim}**${item.proof.length > 0 ? ` Proof: ${item.proof.join('; ')}` : ' (no proof on file: do not state this as fact)'}`);
      }
      out.push('');
    }
    if (positioning.notThis.length > 0) out.push('### What this is not', '', ...bullets(positioning.notThis), '');
  }

  if (spec.personas.length > 0) {
    out.push('## Who we write for', '');
    for (const persona of spec.personas) {
      out.push(`### ${persona.name} (\`${persona.id}\`)`, '');
      if (persona.role) out.push(`Role: ${persona.role}`, '');
      if (persona.description) out.push(persona.description, '');
      if (persona.jobs.length > 0) out.push('Jobs to be done:', '', ...bullets(persona.jobs), '');
      if (persona.pains.length > 0) out.push('Pains:', '', ...bullets(persona.pains), '');
      if (persona.triggers.length > 0) out.push('Triggers:', '', ...bullets(persona.triggers), '');
      if (persona.questions.length > 0) out.push('Questions they ask:', '', ...bullets(persona.questions), '');
    }
  }

  const messaging = spec.messaging;
  if (messaging) {
    if (messaging.pillars.length > 0) {
      out.push('## Messaging pillars', '');
      for (const pillar of messaging.pillars) {
        out.push(`### ${pillar.title} (\`${pillar.id}\`)`, '', pillar.claim, '');
        if (pillar.proof.length > 0) out.push('Proof you may cite:', '', ...bullets(pillar.proof), '');
        else out.push('No proof on file. Do not present this claim as established fact.', '');
        if (pillar.personas.length > 0) out.push(`For: ${pillar.personas.join(', ')}`, '');
      }
    }
    if (messaging.boilerplate.short || messaging.boilerplate.medium) {
      out.push('## Boilerplate', '');
      if (messaging.boilerplate.short) out.push(`Short: ${messaging.boilerplate.short}`, '');
      if (messaging.boilerplate.medium) out.push(`Medium: ${messaging.boilerplate.medium}`, '');
    }
    const { prefer, avoid } = messaging.vocabulary;
    if (prefer.length > 0 || avoid.length > 0) {
      out.push('## Vocabulary', '');
      if (prefer.length > 0) {
        out.push('Say it this way:', '');
        for (const entry of prefer) {
          out.push(`- "${entry.term}", not ${entry.insteadOf.map((value) => `"${value}"`).join(', ')}${entry.reason ? `. ${entry.reason}` : ''}`);
        }
        out.push('');
      }
      if (avoid.length > 0) {
        out.push('Never use:', '');
        for (const entry of avoid) out.push(`- "${entry.term}"${entry.reason ? `. ${entry.reason}` : ''}`);
        out.push('');
      }
    }
    if (messaging.voice.length > 0) out.push('## Voice', '', ...bullets(messaging.voice), '');
  }

  if (spec.topics.length > 0) {
    out.push('## Topics', '');
    for (const topic of spec.topics) {
      const count = items.filter((item) => item.topics.includes(topic.id) && !item.draft).length;
      out.push(`### ${topic.name} (\`${topic.id}\`)`, '');
      if (topic.description) out.push(topic.description, '');
      if (topic.keywords.length > 0) out.push(`Keywords: ${topic.keywords.join(', ')}`, '');
      if (topic.questions.length > 0) out.push('Questions to answer:', '', ...bullets(topic.questions), '');
      out.push(`Published pieces tagged with this topic: ${count}`, '');
    }
  }

  if (spec.competitors.length > 0) {
    out.push('## Alternatives', '', 'Describe alternatives fairly. Compete on the stated difference, not on adjectives.', '');
    for (const competitor of spec.competitors) {
      out.push(`- **${competitor.name}** (${competitor.kind}): ${competitor.summary} How we differ: ${competitor.weDiffer}`);
    }
    out.push('');
  }

  const collections = Object.entries(spec.content.collections);
  if (collections.length > 0) {
    out.push('## Content contract', '', 'Markdown content lives in these collections:', '');
    for (const [name, collection] of collections) {
      out.push(`- \`${collection.path}/\` (${name}, ${collection.type}) publishes at \`${collection.url}\``);
    }
    out.push(
      '',
      'Frontmatter: `title` and `description` are required. Articles need a `date` (YYYY-MM-DD).',
      'Tag content with `topic`, `persona` and `pillar` ids from this file, and list the persona questions it settles under `answers`.',
      '',
      'Rules enforced by `gtm lint`:',
      '',
    );
    for (const rule of RULES) {
      const { severity } = resolveRule(spec, rule, '');
      if (severity !== 'off') out.push(`- \`${rule.id}\` (${severity}): ${rule.description}`);
    }
    out.push('');
  }

  const blocked = crawlerDecisions(spec).filter((decision) => decision.policy === 'disallow');
  out.push(
    '## Crawler policy',
    '',
    `- AI training crawlers: ${spec.crawlers.ai.training}`,
    `- AI search crawlers: ${spec.crawlers.ai.search}`,
    `- User-triggered AI fetchers: ${spec.crawlers.ai.user}`,
  );
  if (blocked.length > 0) out.push(`- Blocked agents: ${blocked.map((decision) => decision.agent).join(', ')}`);
  if (spec.crawlers.disallow.length > 0) out.push(`- Paths closed to all crawlers: ${spec.crawlers.disallow.join(', ')}`);
  out.push(
    '',
    '## Before you finish',
    '',
    'Run `npx gtm check`. It validates the spec, lints the content against it and fails if a generated file is stale.',
    'If it reports a stale file, run `npx gtm build` and commit the result.',
    '',
  );

  return out.join('\n');
}
