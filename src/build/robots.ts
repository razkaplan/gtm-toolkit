import type { Spec } from '../spec/schema';
import { crawlerDecisions } from './crawlers';

const PURPOSES = [
  ['training', 'model training'],
  ['search', 'AI search indexing'],
  ['user', 'user-triggered fetches'],
] as const;

export function buildRobots(spec: Spec, specDir: string): string {
  const lines: string[] = [
    `# Generated by gtm-toolkit from ${specDir}/gtm.yaml. Edit the spec, then run \`gtm build\`.`,
    '',
    'User-agent: *',
    'Allow: /',
    ...spec.crawlers.disallow.map((path) => `Disallow: ${path}`),
    '',
  ];

  const decisions = crawlerDecisions(spec);
  for (const [purpose, label] of PURPOSES) {
    lines.push(`# AI crawlers, ${label}: ${spec.crawlers.ai[purpose]}`);
  }
  const allowed = decisions.filter((decision) => decision.policy === 'allow').map((decision) => decision.agent);
  const blocked = decisions.filter((decision) => decision.policy === 'disallow').map((decision) => decision.agent);
  if (allowed.length > 0) {
    lines.push('# Allowed under the rules above:');
    for (let index = 0; index < allowed.length; index += 5) lines.push(`#   ${allowed.slice(index, index + 5).join(', ')}`);
  }
  lines.push('');

  if (blocked.length > 0) {
    for (const agent of blocked) lines.push(`User-agent: ${agent}`);
    lines.push('Disallow: /', '');
  }

  if (spec.outputs.sitemap !== false) lines.push(`Sitemap: ${spec.site.url}/sitemap.xml`, '');
  return lines.join('\n');
}
